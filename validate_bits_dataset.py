# validate_bits_dataset.py
# Validate a 625-bit Base-626 dataset produced by gen_bit_dataset.py
#
# Checks:
#  - Shapes/dtypes/value ranges
#  - Class coverage & balance
#  - Duplicate bit-vectors across different labels (collisions)
#  - Digit self-consistency: sum(bits)==digit for classes 0..625
#  - (Optional) Symbol parity: PNG -> 25x25 -> bits equals dataset bits
#  - Make small montages for quick human scan
#  - (Optional) quick MLP sanity accuracy
#
# Usage examples:
#   py -3.12 -m pip install numpy pillow scikit-learn
#   py -3.12 validate_bits_dataset.py --data data\\bits --symbols out\\symbols\\decode_table_symbols.json --montages
#   py -3.12 validate_bits_dataset.py --data data\\bits --quick-train

from __future__ import annotations

import argparse, json, hashlib
from pathlib import Path
from typing import Dict, List, Tuple

import numpy as np
from PIL import Image, ImageDraw

from base625_grid import resolve_asset_path

# Optional quick-train
try:
    from sklearn.model_selection import train_test_split
    from sklearn.neural_network import MLPClassifier
    HAVE_SK = True
except Exception:
    HAVE_SK = False

GRID_N = 25

def boolvec_to_grid(bits: np.ndarray) -> np.ndarray:
    """(625,) uint8 -> (25,25) bool (row-major)."""
    g = bits.reshape(GRID_N, GRID_N).astype(bool)
    return g

def grid_to_image(grid: np.ndarray, cell_px: int = 12, draw_grid: bool = False) -> Image.Image:
    n = grid.shape[0]
    W = n * cell_px
    H = n * cell_px
    img = Image.new("RGB", (W + 1, H + 1), (255, 255, 255))
    drw = ImageDraw.Draw(img)
    for r in range(n):
        for c in range(n):
            x0 = c * cell_px
            y0 = r * cell_px
            x1 = x0 + cell_px
            y1 = y0 + cell_px
            fill = (0, 0, 0) if grid[r, c] else (255, 255, 255)
            drw.rectangle([x0, y0, x1, y1], fill=fill)
    if draw_grid:
        for c in range(n + 1):
            x = c * cell_px
            drw.line([(x, 0), (x, H)], fill=(0,0,0), width=1)
        for r in range(n + 1):
            y = r * cell_px
            drw.line([(0, y), (W, y)], fill=(0,0,0), width=1)
    return img

def sample_png_to_grid25(png_path: Path) -> np.ndarray:
    """Rebuild (25,25) bool grid from a PNG generated by the project renderer."""
    im = Image.open(png_path).convert("RGB")
    w, h = im.width, im.height
    cell_px = max(1, round((w - 1) / GRID_N))
    g = np.zeros((GRID_N, GRID_N), dtype=bool)
    for r in range(GRID_N):
        for c in range(GRID_N):
            x = min(w - 1, c * cell_px + cell_px // 2)
            y = min(h - 1, r * cell_px + cell_px // 2)
            R, G, B = im.getpixel((x, y))
            g[r, c] = (R + G + B) < (255 * 3 / 2)
    return g

def sha256_bits(bits: np.ndarray) -> str:
    return hashlib.sha256(bits.astype(np.uint8).tobytes()).hexdigest()

def main():
    ap = argparse.ArgumentParser(description="Validate 625-bit Base-626 dataset")
    ap.add_argument("--data", required=True, help="Folder containing X.npy, y.npy, class_map.json")
    ap.add_argument("--symbols", default="", help="(Optional) symbols decode_table_symbols.json for parity check")
    ap.add_argument("--montages", action="store_true", help="Write small class montages to validation_output/montages")
    ap.add_argument("--quick-train", action="store_true", help="Train a tiny MLP to sanity-check separability")
    ap.add_argument("--montage-classes", type=int, default=12, help="How many classes to montage")
    ap.add_argument("--montage-samples", type=int, default=16, help="Samples per class in montage")
    args = ap.parse_args()

    data_dir = Path(args.data)
    out_dir = data_dir / "validation_output"
    out_dir.mkdir(parents=True, exist_ok=True)

    # -------- Load core files --------
    X_path, Y_path, MAP_path = data_dir/"X.npy", data_dir/"y.npy", data_dir/"class_map.json"
    assert X_path.exists() and Y_path.exists() and MAP_path.exists(), "Missing X.npy / y.npy / class_map.json"

    X = np.load(X_path)  # (N,625) uint8
    y = np.load(Y_path)  # (N,)
    with open(MAP_path, "r", encoding="utf-8") as f:
        class_map: Dict[str, Dict] = json.load(f)

    report_lines: List[str] = []
    def log(line: str):
        print(line)
        report_lines.append(line)

    log(f"Loaded: X={X.shape} dtype={X.dtype}, y={y.shape} dtype={y.dtype}, classes in map={len(class_map)}")

    # Generation settings (written by gen_bit_dataset.py). Noise augmentation
    # changes bit-sums and breaks exact parity, so the checks below adapt.
    noise_flip = 0.0
    meta_path = data_dir / "meta.json"
    if meta_path.exists():
        with open(meta_path, "r", encoding="utf-8") as f:
            noise_flip = float(json.load(f).get("noise_flip", 0.0) or 0.0)
    if noise_flip > 0:
        log(f"Dataset was generated with noise_flip={noise_flip}; using noise-aware tolerances")

    # -------- Schema checks --------
    ok_vals = np.isin(X, [0,1]).all()
    log(f"Values in X are only 0/1: {ok_vals}")
    if not ok_vals:
        bad = int(np.sum(~np.isin(X, [0,1])))
        log(f"  WARNING: found {bad} non-binary entries in X")

    assert X.ndim == 2 and X.shape[1] == 625, "X must be (N,625)"
    assert y.ndim == 1 and y.shape[0] == X.shape[0], "y length must equal N"

    # Coverage
    labels_present = sorted(set(int(v) for v in y.tolist()))
    log(f"Labels present: {len(labels_present)} unique")
    # Verify all labels exist in map
    missing_in_map = [cid for cid in labels_present if str(cid) not in class_map]
    log(f"Labels missing from class_map.json: {missing_in_map}" if missing_in_map else "All labels found in class_map.json")

    # -------- Class balance --------
    counts = np.bincount(y, minlength=max(labels_present)+1)
    present_counts = {cid:int(counts[cid]) for cid in labels_present}
    min_c = min(present_counts.values())
    max_c = max(present_counts.values())
    log(f"Per-class count: min={min_c}, max={max_c}, mean={np.mean(list(present_counts.values())):.2f}")
    # Save a small CSV of counts
    with open(out_dir/"class_counts.csv","w",encoding="utf-8") as f:
        f.write("class_id,type,label_or_digit,count\n")
        for cid in labels_present:
            meta = class_map.get(str(cid), {})
            if meta.get("type") == "DIGIT":
                lab = f"DIGIT_{meta.get('digit')}"
            else:
                lab = meta.get("label", meta.get("symbol","?"))
            f.write(f"{cid},{meta.get('type','?')},{lab},{present_counts[cid]}\n")

    # -------- Bit-label collisions --------
    # Hash each row and see if any hash maps to multiple labels
    hashes = {}
    collisions = []
    for i in range(X.shape[0]):
        h = sha256_bits(X[i])
        lbl = int(y[i])
        if h not in hashes:
            hashes[h] = lbl
        elif hashes[h] != lbl:
            collisions.append((i, lbl, hashes[h]))
    log(f"Bit collisions (same bits, different labels): {len(collisions)}")
    if collisions:
        with open(out_dir/"collisions.txt","w") as f:
            for i, lbl, prev in collisions:
                f.write(f"row={i} label={lbl} prev_label_for_same_bits={prev}\n")

    # -------- Digit self-consistency --------
    # For each digit class 0..625 that appears, check average bit-sum equals the digit
    digit_ids = [cid for cid in labels_present if cid <= 625]
    inconsistent = []
    for d in digit_ids:
        idx = np.where(y == d)[0]
        # take up to 100 samples for speed
        idx = idx[: min(100, len(idx))]
        if idx.size == 0:
            continue
        sums = X[idx].sum(axis=1)  # (k,)
        mean_sum = float(sums.mean())
        # With independent bit flips at rate p, E[sum] = d + p*(625 - 2d).
        expected = d + noise_flip * (625 - 2 * d)
        std = np.sqrt(625 * noise_flip * (1 - noise_flip) / max(1, idx.size))
        atol = 0.1 + 5 * std
        if not np.isclose(mean_sum, expected, atol=atol):
            inconsistent.append((d, mean_sum))
    log(f"Digit self-consistency issues: {len(inconsistent)}")
    if inconsistent:
        with open(out_dir/"digit_inconsistency.txt","w") as f:
            for d, m in inconsistent:
                f.write(f"class {d}: mean bit-sum {m:.3f} vs expected {d}\n")

    # -------- Symbol parity (optional) --------
    if args.symbols:
        sym_json = Path(args.symbols)
        if sym_json.exists():
            with open(sym_json, "r", encoding="utf-8") as f:
                sym_obj = json.load(f)
            # Build map symbol -> png path
            sym_to_png = {}
            for it in sym_obj.get("items", []):
                sym = (it.get("symbol") or "").strip()
                pth = resolve_asset_path(it, sym_json)
                if sym and pth is not None:
                    sym_to_png[sym] = pth
            # Compare first sample per symbol class (if present)
            symbol_mismatches = []
            for cid_str, meta in class_map.items():
                cid = int(cid_str)
                if meta.get("type") != "SYMBOL":
                    continue
                sym = (meta.get("symbol") or "").strip()
                png = sym_to_png.get(sym)
                if png is None:
                    continue
                # find one row with label cid
                idx = np.where(y == cid)[0]
                if idx.size == 0:
                    continue
                row = X[idx[0]]
                g_bits = boolvec_to_grid(row)
                g_png  = sample_png_to_grid25(png)
                hamming = int(np.sum(g_bits != g_png))
                # Allow a few flipped bits when the dataset was noise-augmented.
                max_hamming = 0 if noise_flip <= 0 else int(np.ceil(625 * noise_flip * 5 + 1))
                if hamming > max_hamming:
                    symbol_mismatches.append((cid, sym, str(png)))
            log(f"Symbol grid parity mismatches: {len(symbol_mismatches)}")
            if symbol_mismatches:
                with open(out_dir/"symbol_parity_mismatches.txt","w",encoding="utf-8") as f:
                    for cid, sym, p in symbol_mismatches:
                        f.write(f"class {cid} symbol '{sym}' mismatch vs {p}\n")
        else:
            log(f"(Skip symbol parity) file not found: {sym_json}")

    # -------- Montages (quick visual scan) --------
    if args.montages:
        mdir = out_dir / "montages"
        mdir.mkdir(parents=True, exist_ok=True)
        # Choose some classes: first k digits and first k symbols that exist
        digit_sel = [cid for cid in labels_present if cid <= 625][: args.montage_classes]
        symbol_sel = [cid for cid in labels_present if cid > 625][: args.montage_classes]
        def montage_for_class(cid: int, max_samples: int = 16):
            idx = np.where(y == cid)[0][:max_samples]
            if idx.size == 0:
                return
            imgs = []
            for i in idx:
                g = boolvec_to_grid(X[i])
                imgs.append(grid_to_image(g, cell_px=8, draw_grid=False))
            # stitch into grid 4x4
            cols = 4
            rows = int(np.ceil(len(imgs)/cols))
            w, h = imgs[0].width, imgs[0].height
            out = Image.new("RGB", (cols*w, rows*h), (230,230,230))
            k = 0
            for r in range(rows):
                for c in range(cols):
                    if k >= len(imgs): break
                    out.paste(imgs[k], (c*w, r*h))
                    k += 1
            meta = class_map.get(str(cid), {})
            name = meta.get("label", f"DIGIT_{meta.get('digit')}") if meta.get("type")=="SYMBOL" else f"DIGIT_{meta.get('digit')}"
            out.save(mdir / f"class_{cid:04d}_{name}.png")

        for cid in digit_sel + symbol_sel:
            montage_for_class(cid, max_samples=args.montage_samples)
        log(f"Wrote montages to {mdir}")

    # -------- Quick-train sanity --------
    if args.quick_train:
        if not HAVE_SK:
            log("scikit-learn not installed; skip quick-train.")
        else:
            from sklearn.metrics import classification_report
            Xtr, Xte, ytr, yte = train_test_split(X, y, test_size=0.2, stratify=y, random_state=42)
            clf = MLPClassifier(hidden_layer_sizes=(256,128,64), activation="relu", solver="adam",
                                alpha=1e-4, batch_size=512, max_iter=30, verbose=False)
            clf.fit(Xtr, ytr)
            ypr = clf.predict(Xte)
            rep = classification_report(yte, ypr, digits=4, zero_division=0)
            with open(out_dir/"quick_train_report.txt","w") as f:
                f.write(rep)
            log("Quick-train report written to quick_train_report.txt")

    # -------- Write report --------
    with open(out_dir/"validation_report.txt","w",encoding="utf-8") as f:
        f.write("\n".join(report_lines))
    log(f"Done. Report at {out_dir/'validation_report.txt'}")

if __name__ == "__main__":
    main()
